import sys
import os
sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from geocoding import geocode_venue

def get_coords_for_text(text):
    """
    Scans the text for Venues first, then tries OSM Geocoding, then Zones.
    Returns (lat, lng, name).
    """
    text_lower = text.lower()
    
    # 1. Check Specific Venues (Instant & Verified)
    for venue, coords in BENGALURU_VENUES.items():
        if venue.lower() in text_lower:
            return coords[0], coords[1], venue

    # 2. Try OpenStreetMap Geocoding (High Accuracy, Slower)
    # We try to extract a clean query.
    # If the text is short (< 60 chars), try it directly.
    # Otherwise, try to split by common separators like "," or "-" or "Venue:"
    
    query_candidate = None
    if len(text) < 60:
        query_candidate = text
    else:
        # Try to find a venue name at the start or after "Venue:"
        if "Venue:" in text:
            parts = text.split("Venue:")
            if len(parts) > 1:
                # Take the part after "Venue:", up to the next period or newline
                candidate = parts[1].split(".")[0].split("\n")[0].strip()
                if len(candidate) > 3:
                    query_candidate = candidate
        
        if not query_candidate:
            # Try the first part of the string (often the Title)
            query_candidate = text.split(" - ")[0].split("|")[0].strip()
            if len(query_candidate) > 60:
                query_candidate = query_candidate[:60] # Truncate

    if query_candidate:
        # print(f"Geocoding candidate: {query_candidate}")
        osm_result = geocode_venue(query_candidate)
        if osm_result:
            return osm_result[0], osm_result[1], osm_result[2] # lat, lng, name

    # 3. Check Zones (Neighborhoods)
    for zone, coords in BENGALURU_ZONES.items():
        if zone.lower() in text_lower:
            return coords[0], coords[1], zone
            
    return None
            
    return None
